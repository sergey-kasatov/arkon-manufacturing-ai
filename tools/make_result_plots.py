def load(module, filename):
    path = CKPT_DIR / module / filename
    if not path.exists():
        raise SystemExit(
            "missing %s\nThe metrics files are tracked in git; restore them from the "
            "repository or re-run the module's training script." % path
        )
    return json.loads(path.read_text(encoding="utf-8"))


def save(fig, name, subfolder, source):
    """Stamp the figure with the file it was built from, then write it."""
    fig.text(0.5, -0.045, "generated by tools/make_result_plots.py from %s" % source,
             ha="center", va="bottom", fontsize=8, color="#7b8794")
    out_dir = ASSETS_DIR / subfolder
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / ("%s.png" % name)
    fig.savefig(path, dpi=150, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print("  saved %s" % path.relative_to(PROJECT_ROOT))
    return path


def tidy(ax, grid_axis="y"):
    ax.set_axisbelow(True)
    ax.grid(axis=grid_axis)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)


def candidate_label(entry):
    return "%s\n%s" % (
        "imputed" if entry["median_imputation"] else "NaN kept",
        "class weights" if entry["class_weighting"] else "no weights",
    )


# Scania: the selection is unstable, the threshold is not
def scania_figure(meta):
    selection = meta["selection"]
    candidates = sorted(selection, key=lambda k: selection[k]["mean_out_of_fold_cost"])
    seeds = meta["selection_seeds"]
    x = list(range(len(candidates)))

    fig, (left, right) = plt.subplots(
        1, 2, figsize=(15, 6), gridspec_kw={"width_ratios": [1, 1.2], "wspace": 0.38})

    # Left: one line per fold seed. The crossings are the finding.
    for i, seed in enumerate(seeds):
        costs = [
            next(p["out_of_fold_cost"] for p in selection[c]["per_seed"] if p["fold_seed"] == seed)
            for c in candidates
        ]
        colour = SEED_COLOURS[i % len(SEED_COLOURS)]
        left.plot(x, costs, marker="o", markersize=7, linewidth=1.8, color=colour,
                  label="fold seed %s" % seed, zorder=3)
        best = min(range(len(costs)), key=lambda j: costs[j])
        left.scatter([x[best]], [costs[best]], s=230, facecolors="none", zorder=4,
                     edgecolors=colour, linewidths=2.2)

    means = [selection[c]["mean_out_of_fold_cost"] for c in candidates]
    left.plot(x, means, marker="s", markersize=9, linewidth=2.6, color=INK,
              linestyle="--", label="mean of the three seeds", zorder=5)

    left.set_xticks(x)
    left.set_xticklabels([candidate_label(selection[c]) for c in candidates], fontsize=10)
    left.set_xlim(-0.5, len(candidates) - 0.5)
    left.set_ylim(min(means) - 1400, 38400)
    left.set_ylabel("out-of-fold cost")
    left.set_title("Selection: three fold seeds, three different winners", loc="left")
    left.legend(frameon=False, fontsize=10, loc="upper left")
    left.annotate(
        "circled = that seed's winner\nspread across candidates: %.1f percent"
        % (meta["candidate_spread"] * 100),
        xy=(0.035, 0.71), xycoords="axes fraction", ha="left", va="top",
        fontsize=10, color="#4a5560")
    left.annotate("chosen:\nlowest mean", xy=(x[0], means[0]), xytext=(x[0] + 0.3, means[0] - 1250),
                  fontsize=10, color=INK, arrowprops=dict(arrowstyle="->", color=INK, linewidth=1.2))
    tidy(left)

    # Right: the test set, scored once.
    display = {"logistic_regression": "logistic\nregression"}
    for c in candidates:
        display[c] = candidate_label(selection[c])
    display[meta["chosen"]] = display[meta["chosen"]] + "   (shipped)"
    default_key = [k for k in meta["results"] if "default_threshold" in k][0]
    display[default_key] = "shipped model,\ndefault threshold 0.5"

    rows = sorted(meta["results"].items(), key=lambda kv: kv[1]["cost"], reverse=True)
    costs = [v["cost"] for _, v in rows]
    colours = [
        ALERT if k == default_key else ACCENT if k == meta["chosen"] else NEUTRAL
        for k, _ in rows
    ]

    bars = right.barh(range(len(rows)), costs, color=colours, height=0.62, zorder=3)
    for bar, (_, value) in zip(bars, rows):
        right.text(bar.get_width() + 600, bar.get_y() + bar.get_height() / 2,
                   "{:,}".format(value["cost"]), va="center", fontsize=10.5, color=INK)

    right.set_yticks(range(len(rows)))
    right.set_yticklabels([display.get(k, k) for k, _ in rows], fontsize=10)
    right.set_ylim(-0.7, len(rows) - 0.1)
    right.set_xlim(0, max(costs) * 1.16)

    # The published top three of the same challenge, on the same test set. The
    # three scores sit within 1,560 of each other, so they are labelled once
    # rather than three times.
    ref = meta["published_reference"]
    right.axvspan(ref["best_total_cost"], ref["third"], color="#e7edf1", zorder=0)
    for value in (ref["best_total_cost"], ref["second"], ref["third"]):
        right.axvline(value, color="#6b7680", linestyle=":", linewidth=1.3, zorder=1)
    right.annotate(
        "IDA 2016 challenge, published top three\n%s   %s   %s\nthe shipped model lands between first and second"
        % tuple("{:,}".format(v) for v in (ref["best_total_cost"], ref["second"], ref["third"])),
        xy=(ref["second"], len(rows) - 0.55), xytext=(max(costs) * 0.42, len(rows) - 0.25),
        fontsize=9.5, color="#4a5560", va="center", ha="left",
        arrowprops=dict(arrowstyle="->", color="#8a949c", linewidth=1.2,
                        connectionstyle="arc3,rad=0.15"))

    right.set_xlabel("total cost on the 16,000-row test set\n10 per needless workshop check, 500 per missed failure")
    right.set_title("Test set, scored once", loc="left")
    factor = meta["results"][default_key]["cost"] / meta["results"][meta["chosen"]]["cost"]
    right.text(costs[0] * 0.97, 0,
               "%.1fx the shipped cost.\nSame model, same probabilities,\none decision." % factor,
               ha="right", va="center", fontsize=10.5, color="white", zorder=4)
    tidy(right, grid_axis="x")

    fig.suptitle("Scania APS: the threshold decided the cost, the structure did not",
                 fontsize=15, x=0.045, ha="left", y=1.0)
    return save(fig, "scania_cost_selection", "ml", "models/checkpoints/scania/scania_aps_meta.json")


# Casting: one operating point, and why the assumed cost ratio does not move it
def casting_figure(meta):
    ratios = sorted(int(k.split("_")[-1].rstrip("x")) for k in meta["operating_points"])
    chosen = meta["operating_points"]["missed_defect_costs_%dx" % ratios[0]]
    default = meta["at_threshold_0.5"]

    fig, (left, right) = plt.subplots(
        1, 2, figsize=(13.5, 5.8), gridspec_kw={"width_ratios": [1, 1.2], "wspace": 0.38})

    # Left: the confusion matrix as four labelled cells.
    # Column 0 is what was actually defective, column 1 what was actually good;
    # row 0 is what the model flagged, row 1 what it let through.
    cells = [
        (0, 0, chosen["defects_caught"], "caught", ACCENT, False),
        (0, 1, chosen["defects_missed"], "missed",
         "#3f7d55" if chosen["defects_missed"] == 0 else ALERT, True),
        (1, 0, chosen["good_parts_rejected"], "rejected", "#e08e45", True),
        (1, 1, chosen["good_parts_passed"], "passed", ACCENT, False),
    ]
    for col, row, count, tag, colour, strong in cells:
        left.add_patch(Rectangle((col, -row), 1, 1, facecolor=colour,
                                 alpha=0.9 if strong else 0.18, edgecolor="white", linewidth=3))
        left.text(col + 0.5, -row + 0.6, str(count), ha="center", va="center",
                  fontsize=32, color="white" if strong else INK, fontweight="bold")
        left.text(col + 0.5, -row + 0.28, tag, ha="center", va="center",
                  fontsize=12, color="white" if strong else "#4a5560")

    left.set_xlim(0, 2)
    left.set_ylim(-1, 1)
    left.set_xticks([0.5, 1.5])
    left.set_xticklabels([
        "actually defective\n%d images" % (chosen["defects_caught"] + chosen["defects_missed"]),
        "actually good\n%d images" % (chosen["good_parts_rejected"] + chosen["good_parts_passed"]),
    ])
    left.set_yticks([0.5, -0.5])
    left.set_yticklabels(["flagged\nas defect", "passed to\nthe line"])
    left.tick_params(length=0)
    left.grid(False)
    for side in left.spines.values():
        side.set_visible(False)
    left.set_title("%d test images at threshold %.3f\nROC AUC %.4f, recall %.4f, precision %.4f"
                   % (meta["test_images"], chosen["threshold"], chosen["roc_auc"],
                      chosen["recall"], chosen["precision"]), loc="left")

    # Right: cost is linear in the assumed ratio, so a fixed pair of error counts
    # is one straight line. Zero misses makes that line flat.
    span = list(range(1, 61))
    for point, label, colour, style in (
        (chosen, "chosen threshold %.3f" % chosen["threshold"], ACCENT, "-"),
        (default, "default threshold 0.5", ALERT, "--"),
    ):
        def cost(r, p=point):
            return p["defects_missed"] * r + p["good_parts_rejected"]
        right.plot(span, [cost(r) for r in span], linewidth=2.6, color=colour, linestyle=style,
                   zorder=3, label="%s\n%d missed, %d rejected"
                   % (label, point["defects_missed"], point["good_parts_rejected"]))
        right.scatter(ratios, [cost(r) for r in ratios], s=70, color=colour, zorder=4)
        for r in ratios:
            right.annotate("%d" % cost(r), xy=(r, cost(r)), xytext=(0, 10),
                           textcoords="offset points", ha="center", fontsize=10.5, color=colour)

    swap = (chosen["good_parts_rejected"] - default["good_parts_rejected"]) / max(default["defects_missed"], 1)
    right.axvline(swap, color="#6b7680", linestyle=":", linewidth=1.4)
    right.annotate("below %.0f:1 the default\nthreshold would be cheaper" % swap,
                   xy=(swap + 1.2, right.get_ylim()[1] * 0.62), fontsize=10, color="#4a5560")
    right.set_xlabel("assumed cost of one missed defect, in re-inspected good parts")
    right.set_ylabel("total cost on the test set")
    right.set_xticks([1] + ratios)
    right.set_xticklabels(["1:1"] + ["%d:1" % r for r in ratios])
    right.set_title("Zero misses makes the cost flat,\nso every assumed ratio picks the same threshold", loc="left")
    right.legend(frameon=False, fontsize=10, loc="upper left")
    tidy(right)

    fig.suptitle("Casting defects: no defect reached the line, and 7 good parts paid for it",
                 fontsize=15, x=0.045, ha="left", y=1.0)
    return save(fig, "casting_operating_point", "cv", "models/checkpoints/casting/casting_cv_meta.json")


# CMAPSS: per-subset difficulty, and where the accuracy came from.
# Operating conditions and fault modes are properties of the dataset, not of the
# run, so they are not in the metrics file. Source: the subset table in
# docs/Model_Card_CMAPSS_RUL.md.
SUBSET_SHAPE = {
    "FD001": "1 regime\n1 fault mode",
    "FD002": "6 regimes\n1 fault mode",
    "FD003": "1 regime\n2 fault modes",
    "FD004": "6 regimes\n2 fault modes",
}


def cmapss_figure(meta):
    xgb = meta["results"]["xgboost"]
    lin = meta["results"]["linear_regression"]
    subsets = sorted(xgb["per_subset"])
    x = list(range(len(subsets)))
    width = 0.38

    fig, (left, right) = plt.subplots(
        1, 2, figsize=(15, 5.8), gridspec_kw={"width_ratios": [1.3, 1], "wspace": 0.42})

    lin_rmse = [lin["per_subset"][s]["last_cycle"]["rmse"] for s in subsets]
    xgb_rmse = [xgb["per_subset"][s]["last_cycle"]["rmse"] for s in subsets]
    left.bar([i - width / 2 for i in x], lin_rmse, width, color=NEUTRAL, label="linear regression", zorder=3)
    left.bar([i + width / 2 for i in x], xgb_rmse, width, color=ACCENT, label="XGBoost", zorder=3)
    for i, (a, b) in enumerate(zip(lin_rmse, xgb_rmse)):
        left.text(i - width / 2, a + 0.3, "%.2f" % a, ha="center", fontsize=10, color="#4a5560")
        left.text(i + width / 2, b + 0.3, "%.2f" % b, ha="center", fontsize=10.5, color=INK)

    fleet = xgb["last_cycle"]["rmse"]
    left.axhline(fleet, color=ACCENT, linestyle="--", linewidth=1.6, zorder=2)
    left.text(-0.45, fleet + 0.35, "whole fleet %.2f" % fleet, ha="left", fontsize=10, color=ACCENT)
    left.set_xticks(x)
    left.set_xticklabels(["%s\n%s\n%d test engines" % (s, SUBSET_SHAPE[s], xgb["per_subset"][s]["last_cycle"]["n"])
                          for s in subsets], fontsize=10)
    left.set_ylabel("RMSE in cycles\none prediction per engine at its last cycle")
    left.set_ylim(0, max(lin_rmse) * 1.25)
    left.set_title("One model over all four subsets:\nthe hardest scores about as well as the easiest", loc="left")
    left.legend(frameon=False, fontsize=10, loc="upper left")
    tidy(left)

    ablation = meta["feature_ablation"]
    steps = [
        ("sensors only\n%d features" % ablation["sensors_only"]["n_features"],
         ablation["sensors_only"]),
        ("plus cycle counter\n%d features" % ablation["sensors_plus_cycle"]["n_features"],
         ablation["sensors_plus_cycle"]),
        ("plus %d-cycle window\n%d features" % (ablation["window"],
                                                ablation["with_temporal_features"]["n_features"]),
         ablation["with_temporal_features"]),
    ]
    values = [entry["last_cycle"]["rmse"] for _, entry in steps]
    bars = right.barh(range(len(steps)), values, height=0.55, zorder=3,
                      color=[NEUTRAL, NEUTRAL, ACCENT])
    for i, (bar, value) in enumerate(zip(bars, values)):
        right.text(value + 0.4, bar.get_y() + bar.get_height() / 2, "%.2f" % value,
                   va="center", fontsize=11, color=INK)
        if i:
            right.text(value - 0.5, bar.get_y() + bar.get_height() / 2,
                       "gain %.2f" % (values[i - 1] - value), va="center", ha="right",
                       fontsize=10.5, color="white", zorder=4)
    right.set_yticks(range(len(steps)))
    right.set_yticklabels([label for label, _ in steps], fontsize=10)
    right.invert_yaxis()
    right.set_xlim(0, max(values) * 1.2)
    right.set_xlabel("RMSE in cycles, same metric as the left panel")
    right.set_title("Where the accuracy came from\nablation, all three at the same reduced hyperparameters", loc="left")
    tidy(right, grid_axis="x")

    fig.suptitle("CMAPSS remaining useful life: %d test engines, %d operating regimes"
                 % (meta["test_units"], meta["operating_regimes"]),
                 fontsize=15, x=0.045, ha="left", y=1.0)
    return save(fig, "cmapss_rmse_by_subset", "timeseries",
                "models/checkpoints/cmapss/cmapss_full_fleet_meta.json")


# NEU: the score is real, and most of it was there before training
def neu_figure(meta):
    difficulty = meta["benchmark_difficulty"]
    operating = meta["operating_point"]
    ladder = [
        ("chance\nsix balanced classes", difficulty["chance"], NEUTRAL),
        ("two pixel statistics\nlogistic regression", difficulty["two_feature_pixel_baseline"], NEUTRAL),
        ("frozen backbone\nonly the last layer fitted", meta["ablation_frozen_backbone"]["test_accuracy"], NEUTRAL),
        ("1-nearest-neighbour\nuntrained ImageNet features", difficulty["one_nearest_neighbour_on_imagenet_features"], ALERT),
        ("fine-tuned end to end\nthe shipped module", meta["test_performance"]["accuracy"], ACCENT),
    ]

    fig, (left, right) = plt.subplots(1, 2, figsize=(13.5, 4.9),
                                      gridspec_kw={"width_ratios": [1.55, 1]})

    labels = [label for label, _, _ in ladder]
    values = [value for _, value, _ in ladder]
    colours = [colour for _, _, colour in ladder]
    bars = left.barh(range(len(ladder)), values, color=colours, height=0.62)
    for i, (bar, value) in enumerate(zip(bars, values)):
        left.text(value + 0.012, bar.get_y() + bar.get_height() / 2, "%.4f" % value,
                  va="center", fontsize=10.5, color=INK)
    left.set_yticks(range(len(ladder)))
    left.set_yticklabels(labels, fontsize=9.5)
    left.invert_yaxis()
    left.set_xlim(0, 1.14)
    left.set_xlabel("accuracy on the %d held-out images" % meta["test_images"])
    left.set_title("Most of this task was solved before any training\n"
                   "every row scored on the same folder", loc="left")
    tidy(left, grid_axis="x")

    # The point of the panel is how little headroom is left above the untrained
    # classifier, so mark that level across every row rather than annotating a gap
    # too narrow to draw.
    untrained = difficulty["one_nearest_neighbour_on_imagenet_features"]
    shipped = meta["test_performance"]["accuracy"]
    left.axvline(untrained, color=ALERT, linestyle=":", linewidth=1.4, zorder=0)
    left.text(untrained - 0.02, -0.62,
              "no training at all reaches here;\nfine-tuning adds the last %.4f"
              % (shipped - untrained),
              ha="right", va="top", fontsize=9.5, color=ALERT)

    sent = operating["test_images_sent_to_a_person"]
    logged = meta["test_images"] - sent
    wedges = right.barh([1, 0], [logged, sent], color=[ACCENT, ALERT], height=0.5)
    for bar, value, tag in zip(wedges, (logged, sent), ("P3", "P2")):
        right.text(value + 6, bar.get_y() + bar.get_height() / 2, "%s   %d" % (tag, value),
                   va="center", fontsize=11, color=INK)
    right.set_yticks([0, 1])
    right.set_yticklabels(["below the band edge\na person classifies it",
                           "at or above it\nlogged against the coil"], fontsize=9.5)
    right.set_xlim(0, meta["test_images"] * 1.12)
    right.set_xlabel("events published, one per classified surface")
    basis = "declared, not calibrated" if operating["rule_degenerated"] else "calibrated on the selection set"
    right.set_title("What the module sends an operator\nband edge %.2f, %s"
                    % (operating["confidence_threshold"], basis), loc="left")
    tidy(right, grid_axis="x")

    fig.suptitle("NEU steel surface defects: six classes, %d held-out images"
                 % meta["test_images"], fontsize=15, x=0.045, ha="left", y=1.0)
    fig.tight_layout()
    return save(fig, "neu_benchmark_ladder", "cv",
                "models/checkpoints/neu/neu_cv_meta.json")


# MVTec: four detectors, and what the skeleton design would have scored
def mvtec_figure(meta):
    categories = meta["categories"]
    ladder = meta["benchmark_difficulty"]["image_auroc"]
    performance = meta["test_performance"]["per_category"]
    bands = meta["priority_bands"]

    order = ["pixel mean and sd", "layer4 averaged", "layer4 patches", "layer2+3 patches"]
    colours = {"layer2+3 patches": ACCENT, "layer4 averaged": ALERT}
    labels = {
        "pixel mean and sd": "two pixel statistics\nnearest neighbour",
        "layer4 averaged": "layer4 averaged over the frame\nthe skeleton in the repository",
        "layer4 patches": "layer4 patches\nthe grid, eight times coarser",
        "layer2+3 patches": "layer2 and layer3 patches\nthe shipped module",
    }

    fig, (left, right) = plt.subplots(1, 2, figsize=(13.5, 4.9),
                                      gridspec_kw={"width_ratios": [1.55, 1]})

    means = [ladder[name]["mean"] for name in order]
    bars = left.barh(range(len(order)), means,
                     color=[colours.get(name, NEUTRAL) for name in order], height=0.62)
    for row, name in enumerate(order):
        spread = [ladder[name][category] for category in categories]
        left.scatter(spread, [row] * len(spread), s=18, color=INK, zorder=3, alpha=0.75)
        left.text(max(spread) + 0.02, row, "%.4f" % ladder[name]["mean"],
                  va="center", fontsize=10.5, color=INK)
    left.set_yticks(range(len(order)))
    left.set_yticklabels([labels[name] for name in order], fontsize=9.5)
    left.set_xlim(0, 1.2)
    left.axvline(0.5, color=NEUTRAL, linestyle=":", linewidth=1.2, zorder=0)
    left.text(0.5, len(order) - 0.42, " chance", fontsize=9, color=NEUTRAL, va="top")
    left.set_xlabel("image AUROC: bar is the mean of four categories, dots are the categories")
    left.set_title("The same frozen features, reduced four ways\n"
                   "every row scored on the same four test folders", loc="left")
    tidy(left, grid_axis="x")

    # Right: what an operator receives, per category, and what never arrives
    published_p2 = [bands[category]["P2"] for category in categories]
    published_p3 = [bands[category]["P3"] for category in categories]
    missed = [performance[category]["defects_total"] - performance[category]["defects_found"]
              for category in categories]
    positions = range(len(categories))
    right.barh(positions, published_p2, color=ALERT, height=0.55, label="P2  no sound part scored this high")
    right.barh(positions, published_p3, left=published_p2, color=ACCENT, height=0.55,
               label="P3  above the threshold, inside the sound range")
    widest = max(p2 + p3 for p2, p3 in zip(published_p2, published_p3))
    for row, category in enumerate(categories):
        total = published_p2[row] + published_p3[row]
        right.text(total + widest * 0.03, row,
                   "%d events, %d defect%s not flagged"
                   % (total, missed[row], "" if missed[row] == 1 else "s"),
                   va="center", fontsize=9, color=INK)
    right.set_yticks(list(positions))
    right.set_yticklabels(categories, fontsize=10)
    right.set_xlim(0, widest * 1.75)
    # The annotations run to the right of every bar, so the legend needs a row of its
    # own below the bottom one rather than a corner of the plotting area.
    right.set_ylim(-1.15, len(categories) - 0.45)
    right.set_xlabel("events published; sound parts are suppressed and never sent")
    right.legend(fontsize=8.5, loc="lower right", frameon=False)
    right.set_title("What each detector sends an operator\n"
                    "both band edges are quantiles of held-out sound parts", loc="left")
    tidy(right, grid_axis="x")

    fig.suptitle("MVTec AD: four component categories, mean image AUROC %.4f, "
                 "mean pixel AUROC %.4f"
                 % (meta["test_performance"]["mean_image_auroc"],
                    meta["test_performance"]["mean_pixel_auroc"]),
                 fontsize=15, x=0.045, ha="left", y=1.0)
    fig.tight_layout()
    return save(fig, "mvtec_benchmark_ladder", "cv",
                "models/checkpoints/mvtec/mvtec_cv_meta.json")


# GC10: the per-class spread is mostly the denominators, and what a detector claims
def gc10_figure(meta):
    performance = meta["test_performance"]
    operating = meta["operating_point"]
    classes = meta["classes"]
    per_class = performance["per_class_ap_50"]
    per_boxes = performance["per_class_boxes"]

    # A class the test split does not contain has no AP. There should be none, and a
    # figure that silently dropped one would hide exactly the thing worth seeing.
    scored = sorted((class_id for class_id, ap in per_class.items() if ap is not None),
                    key=lambda class_id: per_class[class_id])
    absent = [class_id for class_id, ap in per_class.items() if ap is None]

    fig, (left, right) = plt.subplots(1, 2, figsize=(13.5, 4.9),
                                      gridspec_kw={"width_ratios": [1.5, 1]})

    values = [per_class[class_id] for class_id in scored]
    boxes = [per_boxes[class_id] for class_id in scored]
    # The panel exists to say that the thin rows are thin because of their
    # denominators, so the bars are coloured by how many boxes stand behind them
    # rather than by how well they scored.
    thin = [n < 20 for n in boxes]
    bars = left.barh(range(len(scored)), values,
                     color=[ALERT if is_thin else ACCENT for is_thin in thin], height=0.62)
    for bar, value in zip(bars, values):
        left.text(value + 0.015, bar.get_y() + bar.get_height() / 2, "%.3f" % value,
                  va="center", fontsize=10, color=INK)
    left.set_yticks(range(len(scored)))
    left.set_yticklabels(["%s  n=%d" % (classes[class_id].replace("_", " "),
                                        per_boxes[class_id]) for class_id in scored],
                         fontsize=9.5)
    left.set_xlim(0, 1.14)
    left.axvline(performance["map_50"], color=INK, linestyle=":", linewidth=1.4, zorder=0)
    # The mean is never below the smallest class AP and the rows are drawn ascending,
    # so the space just right of the line on the bottom row is clear in every run.
    left.text(performance["map_50"] + 0.012, 0, "mAP %.3f" % performance["map_50"],
              fontsize=9.5, color=INK, va="center")
    left.set_xlabel("average precision at IoU 0.5, on the held-out coils")
    left.set_title("Ten classes, red where under twenty boxes stand behind the score\n"
                   "and the count is not what orders them, see the panel on the right",
                   loc="left")
    tidy(left, grid_axis="x")

    # Right: the box ledger. A detector's honest summary is what it found, what it
    # missed and what it claimed that was not there, drawn on one scale.
    found = performance["boxes_found"]
    missed = performance["boxes_present"] - found
    claimed = performance["boxes_claimed_not_there"]
    published = operating["test_sheets_published"]
    silent = operating["test_sheets_silent"]

    right.barh([2], [found], color=ACCENT, height=0.55)
    right.barh([2], [missed], left=[found], color=FAINT, height=0.55)
    right.barh([1], [claimed], color=ALERT, height=0.55)
    right.barh([0], [published], color=ACCENT, height=0.55)
    right.barh([0], [silent], left=[published], color=NEUTRAL, height=0.55)

    widest = max(performance["boxes_present"], claimed, published + silent)
    right.text(performance["boxes_present"] + widest * 0.03, 2,
               "%d found, %d missed" % (found, missed), va="center", fontsize=9.5, color=INK)
    right.text(claimed + widest * 0.03, 1, "%d claimed, nothing there" % claimed,
               va="center", fontsize=9.5, color=INK)
    right.text(published + silent + widest * 0.03, 0,
               "%d publish, %d stay silent" % (published, silent),
               va="center", fontsize=9.5, color=INK)
    right.set_yticks([2, 1, 0])
    right.set_yticklabels(["boxes that are there\n%d annotated" % performance["boxes_present"],
                           "boxes that are not",
                           "sheets, one event each"], fontsize=9.5)
    # The annotations run to the right of every bar, so the axis needs headroom; the
    # label has to stay short enough to fit inside the figure at that width.
    right.set_xlim(0, widest * 1.9)
    right.set_ylim(-0.7, 2.7)
    right.set_xlabel("count, at a detection threshold of %.2f"
                     % operating["detection_threshold"])
    right.set_title("What the module claims, and what it lets past\n"
                    "precision %.3f, recall %.3f"
                    % (performance["precision_at_threshold"],
                       performance["recall_at_threshold"]), loc="left")
    tidy(right, grid_axis="x")

    note = "" if not absent else "  (%d class(es) absent from the test split)" % len(absent)
    fig.suptitle("GC10-DET: ten defect classes located on %d held-out sheets, mAP@0.5 %.4f%s"
                 % (meta["split"]["sheets"]["test"], performance["map_50"], note),
                 fontsize=15, x=0.045, ha="left", y=1.0)
    fig.tight_layout()
    return save(fig, "gc10_detection_ledger", "cv",
                "models/checkpoints/gc10/gc10_cv_meta.json")


