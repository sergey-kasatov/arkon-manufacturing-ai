"""Export the prompts that are actually on the deployed canvas.

A written record of "the final system prompt" assembled by hand agrees with the
canvas on the day it is written and drifts afterwards. The prompt files under
`langflow/prompts/` are the build input, not proof of what is deployed.

So this reads the flow JSON instead: every route description, every specialist
system prompt and every fixed reply, in canvas order. What it prints is what is
deployed, by construction.

Run it from the repository root:

    python langflow/build/export_prompts.py > ../out.md
"""

import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
FLOW = REPO / "langflow" / "arkon_quality_assistant.json"

# template field -> heading shown for it
PROMPT_FIELDS = [
    ("system_prompt", "System prompt"),
    ("agent_instructions", "Agent instructions"),
    ("input_value", "Fixed reply"),
]


def main():
    flow = json.loads(FLOW.read_text(encoding="utf-8"))
    nodes = flow["data"]["nodes"]

    out = []
    out.append("# Final prompts, read out of the deployed canvas")
    out.append("")
    out.append("Generated by `langflow/build/export_prompts.py` from")
    out.append("`langflow/arkon_quality_assistant.json`, so it cannot disagree with what runs.")
    out.append("Canvas `%s`, %d nodes." % (flow.get("name", "?"), len(nodes)))
    out.append("")

    # the router first: its route descriptions are the classification surface
    for node in nodes:
        data = node["data"]["node"]
        routes = data.get("template", {}).get("routes", {}).get("value")
        if not isinstance(routes, list) or not routes:
            continue
        out.append("## Intent router: the classification surface")
        out.append("")
        out.append("Five routes. A message is classified into exactly one. The descriptions are")
        out.append("the whole of the routing logic; there is no rule anywhere else.")
        out.append("")
        for route in routes:
            out.append("### Route: %s" % route.get("route_category", "?"))
            out.append("")
            out.append("```text")
            out.append(route.get("route_description", "").strip())
            out.append("```")
            fixed = (route.get("output_value") or "").strip()
            if fixed:
                out.append("")
                out.append("Fixed message carried on this route, so it reaches its output with no")
                out.append("model call:")
                out.append("")
                out.append("```text")
                out.append(fixed)
                out.append("```")
            out.append("")

    for node in nodes:
        data = node["data"]["node"]
        name = data.get("display_name") or node["id"]
        template = data.get("template", {})
        for field, heading in PROMPT_FIELDS:
            value = template.get(field, {}).get("value")
            if not isinstance(value, str) or len(value.strip()) < 60:
                continue
            out.append("## %s" % name)
            out.append("")
            out.append("*%s*" % heading)
            out.append("")
            out.append("```text")
            out.append(value.strip())
            out.append("```")
            out.append("")

    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
